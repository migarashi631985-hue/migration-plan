    # 6 CPR
    "心肺蘇生、CPRの基本です。"
    "意識がなく、呼吸がない、または、あえぎ呼吸のとき、直ちに胸骨圧迫を開始します。"
    "胸の中央、乳頭を結ぶ線、胸骨の下半分。"
    "圧迫の深さ、約5センチ、小柄な方は4から6センチを目安。"
    "圧迫のテンポ、1分間に100から120回。曲『アンパンマンのマーチ』『うさぎとかめ』のテンポが目安。"
    "人工呼吸ができる場合は、30対2。できない・感染リスクがあるときは、圧迫のみを続けます。",

