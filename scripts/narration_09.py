    "ステップ2、パッドを貼る。右胸の上と、左わき腹。"
    "ステップ3、解析中は体に触れない。"
    "ステップ4、ショック指示が出たら、周囲に離れるよう声をかけてから、ボタンを押す。"
    "ステップ5、ショック後、ただちに胸骨圧迫を再開。"
    "AEDは、迷わず指示に従えば、素人でも安全に使えます。音声ガイダンスに従うだけです。",

