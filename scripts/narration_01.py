    "人の生命、身体、財産の保護のために必要な場合。"
    "公衆衛生の向上、児童の健全育成のために必要な場合。"
    "本人の同意を得るのが困難な、認知症、意識不明などのケース。"
    "それでも、家族への連絡、医療機関への情報提供、原則、事前の包括同意を取っておきます。",

