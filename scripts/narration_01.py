    "個人情報の取得と、同意の取り方です。"
    "取得時、利用目的を明示する。介護サービス提供のため、医療連携のため、緊急時の家族連絡のため、など具体的に。"
    "同意書を取得する。書面で、明示的に。サインをもらう。"
    "目的外の利用は禁止。例えば、介護のために取得した情報を、施設のPRに使う、はNG。"
    "新たな利用が必要になったら、改めて同意を取り直します。",

