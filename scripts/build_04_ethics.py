"""4月　倫理・法令遵守　スライド生成."""
from pathlib import Path

from slide_utils import (
    DeckMeta,
    add_case_slide,
    add_check_slide,
    add_objective_slide,
    add_qa_slide,
    add_section_slide,
    add_summary_slide,
    add_title_slide,
    add_twocol_slide,
    finalise,
    new_presentation,
    save,
)

META = DeckMeta(
    month="4月",
    theme="倫理・法令遵守",
    subtitle="利用者の尊厳を守り、守秘義務を徹底する",
    method="集合研修・個別確認",
    required=False,
    filename="04_倫理・法令遵守.pptx",
    objectives=[
        "介護職員としての倫理綱領の要点を3つ説明できる",
        "利用者の尊厳を守る具体的な言動を挙げられる",
        "守秘義務の対象と違反時の影響を理解している",
        "ヒヤリ事例を倫理・法令の観点から振り返られる",
    ],
)


def build():
    prs = new_presentation()

    add_title_slide(prs, META)
    add_objective_slide(prs, META)

    add_section_slide(
        prs, META,
        "1. 介護職員の倫理綱領（日本介護福祉士会）",
        [
            "利用者本位の立場に立ち、自立支援を行う",
            "専門的サービスの提供と質の向上に努める",
            "プライバシーの保護と情報の適正管理",
            "総合的サービスを提供するための連携協働",
            "利用者ニーズの代弁と、後継者の育成",
        ],
        note="倫理綱領は「やってはいけない」ではなく「目指す姿」を示すもの。",
    )

    add_twocol_slide(
        prs, META,
        "2. 利用者の尊厳を守るとは",
        "尊厳を守る関わり（○）",
        [
            "名前で呼ぶ（○○さん）",
            "ケア前に必ず声かけ・同意確認",
            "排泄・入浴時はカーテン・タオルで配慮",
            "選択肢を示し、ご本人が決める",
            "年齢相応の言葉づかい（敬語）",
        ],
        "尊厳を損なう関わり（×）",
        [
            "ちゃん・あだ名・「おばあちゃん」",
            "無言でケアを始める・身体を動かす",
            "居室のドアを開けたまま排泄介助",
            "「ダメ」「早くして」と否定・急かす",
            "子ども扱いの言葉（タメ口・命令形）",
        ],
    )

    add_section_slide(
        prs, META,
        "3. 守秘義務（介護保険法・個人情報保護法）",
        [
            "対象：氏名・住所・家族・病名・要介護度・ケア内容 等",
            "在職中だけでなく退職後も守秘義務は継続する",
            "SNS・写真投稿は本人・家族の同意が必要",
            "訪問者や他利用者への情報の漏えいも違反にあたる",
            "違反した場合：懲戒処分・損害賠償・刑事罰の対象",
        ],
        note="「うっかり話した」も違反。廊下・休憩室・院外での会話に注意。",
    )

    add_case_slide(
        prs, META,
        "4. 事例検討：居酒屋での会話",
        "勤務後、同僚2人と居酒屋へ行った。隣席のお客に聞こえる声量で "
        "「今日の○○さん、また失禁しちゃって大変だった」と話した。"
        "翌週、その利用者のご家族から施設に「うちの母の話を外でしているのか」"
        "と苦情の電話があった。",
        [
            "どの行為が守秘義務違反にあたりますか？",
            "同僚と情報共有が必要なときは、どこで・どのように行うべきですか？",
            "自分の施設で起きないようにするために、今日からできる対策を1つ挙げてください。",
        ],
    )

    add_section_slide(
        prs, META,
        "5. 関係法令の最低ライン",
        [
            "介護保険法（サービス基準・人員配置・記録保存）",
            "老人福祉法（措置・虐待防止の基本理念）",
            "高齢者虐待防止法（通報義務・早期発見）",
            "個人情報保護法（取得目的の明示・適正管理）",
            "労働基準法・労働安全衛生法（職員自身を守る）",
        ],
        note="迷ったら「利用者にとって最善か」「説明できる行為か」で判断する。",
    )

    add_check_slide(
        prs, META,
        [
            "利用者をフルネーム＋「さん」で呼んでいる",
            "ケア前に必ず声かけと同意確認をしている",
            "居室・浴室・トイレでプライバシー配慮ができている",
            "家族・利用者情報を施設外で話題にしていない",
            "SNSに業務に関する投稿をしていない",
            "記録物（ノート・スマホ）を放置せず鍵付き管理している",
        ],
    )

    add_summary_slide(
        prs, META,
        [
            "倫理は「目指す姿」、法令は「最低ライン」。両方を意識する",
            "尊厳を守る第一歩は『呼び方』と『声かけ』",
            "守秘義務は退職後も続く。施設外での会話・SNSに注意",
            "迷ったら上司・相談窓口に確認（ひとりで判断しない）",
        ],
        next_action=(
            "① 明日から利用者を「○○さん」と呼び、ケア前の声かけを徹底する。"
            "② 休憩室・施設外では利用者の個人情報を話題にしない。"
            "③ 気になる事例があったら記録し、次回のカンファレンスで共有する。"
        ),
    )

    add_qa_slide(prs, META)

    finalise(prs)

    out = Path(__file__).resolve().parent.parent / "slides" / META.filename
    save(prs, out)
    print(f"created: {out}")


if __name__ == "__main__":
    build()
