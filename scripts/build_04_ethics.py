"""4月　倫理・法令遵守　スライド生成（詳細版・事例多め）."""
from pathlib import Path

from slide_utils import (
    DeckMeta,
    add_case_slide,
    add_check_slide,
    add_objective_slide,
    add_qa_slide,
    add_section_slide,
    add_summary_slide,
    add_title_slide,
    add_twocol_slide,
    finalise,
    new_presentation,
    save,
)
from narration_04 import NARRATION_04
from narration_utils import attach_narration

META = DeckMeta(
    month="4月",
    theme="倫理・法令遵守",
    subtitle="利用者の尊厳を守り、守秘義務を徹底する",
    method="集合研修・個別確認（施設内）",
    required=False,
    filename="04_倫理・法令遵守.pptx",
    objectives=[
        "介護職員の倫理綱領の5つの柱を具体例とともに説明できる",
        "尊厳を守る関わりと、傷つける関わりを見分けられる",
        "守秘義務の対象・範囲・違反時のリスクを理解する",
        "SNS・施設外での情報漏えいを防ぐ具体策を挙げられる",
        "倫理的ジレンマに出会ったとき、判断の手順を踏める",
    ],
)


def build():
    prs = new_presentation()

    # 1 表紙
    add_title_slide(prs, META)

    # 2 目的
    add_objective_slide(prs, META)

    # 3 介護倫理とは
    add_section_slide(
        prs, META,
        "1. そもそも「介護倫理」とは",
        [
            "倫理＝「人としてどうあるべきか」を示す行動の指針",
            "法令（最低ライン）を超えて、質の高いケアを目指すもの",
            "『利用者の立場』『専門職としての責務』『社会からの信頼』の3視点",
            "違反しても罰はないが、信頼を失う＝施設運営を揺るがす",
            "現場の迷いを減らすために、仲間と共通認識を持つことが重要",
        ],
        note="倫理は正解を与えるものではなく、迷ったときに戻る「ものさし」。",
    )

    # 4 倫理綱領 前半
    add_section_slide(
        prs, META,
        "2. 倫理綱領 ① 利用者本位・専門性・情報管理",
        [
            "① 利用者本位：利用者の自己決定を尊重し、残存能力を活かす支援",
            "　例）献立・入浴順・レクへの参加可否を本人に確認してから進める",
            "② 専門的サービス：根拠ある技術・知識で、安全にケアを提供する",
            "　例）移乗・食事介助の手順書に沿う／研修で学んだ最新の方法に更新",
            "③ プライバシー保護：得た情報は業務に必要な範囲でのみ共有する",
            "　例）申し送りは人目・人耳のない場所で、記録物は施錠管理",
        ],
    )

    # 5 倫理綱領 後半
    add_section_slide(
        prs, META,
        "3. 倫理綱領 ② 連携協働・代弁と育成",
        [
            "④ 連携協働：医療・看護・リハ・家族・地域と情報共有し、一人で抱えない",
            "　例）服薬変更時は看護師と必ずダブルチェック／家族面談で方針確認",
            "⑤ 利用者ニーズの代弁：話せない・伝えられない想いを代わりに届ける",
            "　例）「痛いかも」「本当は帰りたい」のサインを表情・食欲から汲み取る",
            "⑥ 後継者育成：新人・実習生にも尊厳ある態度で接し、技術と倫理を伝える",
            "　例）新人の前で利用者を呼び捨てにしない（見て真似される）",
        ],
    )

    # 6 尊厳を守る / 損なう関わり
    add_twocol_slide(
        prs, META,
        "4. 利用者の尊厳を守るとは",
        "尊厳を守る関わり（○）",
        [
            "氏名＋「さん」で呼ぶ",
            "ケア前に必ず声かけ・同意確認",
            "排泄・入浴時はカーテン・タオルで配慮",
            "選択肢を示し、ご本人が決める",
            "年齢相応の言葉づかい（敬語）",
            "失敗を責めない／できたことを言葉にする",
        ],
        "尊厳を損なう関わり（×）",
        [
            "ちゃん・あだ名・「おばあちゃん」",
            "無言でケアを始める・体を動かす",
            "居室のドアを開けたまま排泄介助",
            "「ダメ」「早くして」と否定・急かす",
            "子ども扱いの言葉（タメ口・命令形）",
            "他職員・他利用者の前での叱責",
        ],
    )

    # 7 事例①：呼称
    add_case_slide(
        prs, META,
        "5. 事例① 呼び方の問題",
        "新人職員のAさんは、明るく親しみやすい性格。利用者の田中花子さん（85歳）を"
        "「はなちゃん」と呼んでいる。田中さんは笑顔で応じているが、家族が来訪した際、"
        "「母を子ども扱いしないでほしい」と不快感を示された。Aさんは"
        "「本人が嫌がっていないのに、なぜ？」と納得がいかない様子。",
        [
            "「本人が嫌がっていない」なら問題ないと言えますか？",
            "家族が不快に感じた理由を、尊厳の観点から説明してください。",
            "Aさんに対してどのような言葉でフィードバックしますか？",
        ],
    )

    # 8 事例②：入浴介助
    add_case_slide(
        prs, META,
        "6. 事例② 入浴介助の場面",
        "浴室で利用者Bさん（女性・認知症あり）を介助中、男性職員Cさんが"
        "タオルを取りに脱衣所のドアを開けたまま出入りした。Bさんの裸体が廊下から"
        "一瞬見える状態だった。Cさんは「認知症だから気づかないし、急いでいたから」"
        "と話している。",
        [
            "Cさんの言い分は倫理的に妥当ですか？その理由は？",
            "この場面で守るべき「尊厳」「プライバシー」とは具体的に何ですか？",
            "同様の事故を防ぐため、浴室前の運用ルールをどう変えますか？",
        ],
    )

    # 9 守秘義務の基礎
    add_section_slide(
        prs, META,
        "7. 守秘義務の基礎（法的根拠）",
        [
            "介護保険法 第69条の38：「正当な理由なく、業務上知り得た秘密を漏らしてはならない」",
            "介護福祉士法 第46条：守秘義務違反に 1年以下の懲役／30万円以下の罰金",
            "個人情報保護法：取得・利用・提供に本人同意が原則必要",
            "在職中だけでなく『退職後も』守秘義務は継続する",
            "施設の就業規則にも守秘義務違反は懲戒事由として明記されている",
        ],
        note="『知らなかった』は通用しない。入職時に同意書にサインしている。",
    )

    # 10 守秘義務の対象
    add_twocol_slide(
        prs, META,
        "8. 守秘義務の対象・範囲",
        "対象になる情報",
        [
            "氏名・住所・電話番号・生年月日",
            "家族構成・職業・経済状況",
            "病名・服薬・既往歴・検査値",
            "要介護度・ADL・認知症の有無",
            "ケア内容・排泄・入浴の様子",
            "写真・動画・記録物",
        ],
        "漏えいが起きやすい場面",
        [
            "送迎中の車内での会話",
            "エレベーター・廊下・休憩室",
            "家族や友人への「今日の出来事」",
            "SNS（匿名でも特定される）",
            "置き忘れたスマホ・記録ノート",
            "退職後の元同僚との飲み会",
        ],
    )

    # 11 違反時の影響
    add_section_slide(
        prs, META,
        "9. もし守秘義務違反が起きたら",
        [
            "本人・家族への謝罪と説明（施設長・管理者対応）",
            "行政への報告・場合により監査・指定取消のリスク",
            "職員個人：懲戒処分（戒告〜懲戒解雇）・損害賠償請求",
            "刑事罰：1年以下の懲役／30万円以下の罰金（介護福祉士法）",
            "施設の信頼失墜 → 入居率低下・採用困難 → 施設運営そのものが揺らぐ",
        ],
        note="影響は「個人」で終わらない。仲間と施設全体に及ぶ。",
    )

    # 12 事例③：居酒屋
    add_case_slide(
        prs, META,
        "10. 事例③ 居酒屋での会話",
        "勤務後、同僚2人と居酒屋へ行った。隣席に聞こえる声量で"
        "「今日の田中さん、また失禁しちゃって大変だった」と話した。"
        "翌週、田中さんのご家族から施設に「うちの母の話を外でしているのか」"
        "と苦情の電話があった。隣席の客が家族の知人だった。",
        [
            "どの行為が守秘義務違反にあたりますか？（複数）",
            "同僚と情報共有が必要なとき、どこで・どのように行うべきですか？",
            "同じ失敗をしないために、今日からできる個人のルールを1つ決めてください。",
        ],
    )

    # 13 事例④：SNS
    add_case_slide(
        prs, META,
        "11. 事例④ SNSへの写真投稿",
        "職員Dさんが、夏祭りイベントで撮った利用者との集合写真をInstagramに"
        "投稿した。アカウントは鍵なし。ハッシュタグに施設名を入れていた。"
        "「楽しそうな様子を家族にも見てほしかった」とのこと。写真には"
        "認知症の利用者も複数写り込んでおり、家族の同意は得ていなかった。",
        [
            "この投稿にはどんな問題がありますか？（個人情報／肖像権／守秘義務）",
            "写真を使って発信したい場合、事前にどんな手続きが必要ですか？",
            "施設としてSNS利用ルールを作るなら、どんな項目を入れますか？",
        ],
    )

    # 14 事例⑤：家族からの電話
    add_case_slide(
        prs, META,
        "12. 事例⑤ 家族からの電話照会",
        "夜勤中、「○○さんの息子です。母の今日の様子を教えてください」"
        "と電話があった。普段のキーパーソンは娘さん。息子さんの連絡先は"
        "記録になく、声も初めて聞く。時間が遅く、上司には連絡しづらい。"
        "Eさんはつい「今日は食事を半分残しました」と答えてしまった。",
        [
            "Eさんの対応の問題点は何ですか？",
            "電話の相手が本当に家族かどうか、どう確認すべきですか？",
            "施設として「電話での情報提供ルール」を決めるなら何を入れますか？",
        ],
    )

    # 15 倫理的ジレンマ フレーム
    add_section_slide(
        prs, META,
        "13. 倫理的ジレンマに出会ったら（判断の手順）",
        [
            "Step1：事実を整理する（誰が・何を・どこで・いつ・なぜ）",
            "Step2：関係する原則を挙げる（自己決定／安全／尊厳／公平）",
            "Step3：選択肢を複数出す（A案・B案・C案）",
            "Step4：それぞれの利点・リスクを比較する",
            "Step5：一人で決めず、上司・多職種に相談する",
            "Step6：決めた理由を『記録』に残す（後から検証できるように）",
        ],
        note="迷う＝倫理的に考えている証拠。迷ったら相談が正解。",
    )

    # 16 事例⑥：ジレンマ
    add_case_slide(
        prs, META,
        "14. 事例⑥ 本人の希望 vs 安全",
        "利用者Fさん（80歳男性・軽度認知症）は「毎日散歩に行きたい」と強く希望する。"
        "しかし最近、道に迷い警察に保護されたことがある。家族は「もう外出させないで」"
        "と依頼。本人は「家に閉じ込められるなんてひどい」と怒っている。",
        [
            "自己決定の尊重と、安全確保はどちらを優先すべきでしょうか？",
            "『外出ゼロ』『完全自由』以外に、どんな第3の選択肢がありますか？",
            "あなたが担当者なら、家族・本人・多職種でどんな合意形成を図りますか？",
        ],
    )

    # 17 関係法令
    add_section_slide(
        prs, META,
        "15. 関係法令の最低ライン",
        [
            "介護保険法：サービス基準・人員配置・記録保存・秘密保持",
            "老人福祉法：福祉の理念・措置の枠組み",
            "高齢者虐待防止法：通報義務・早期発見・使用者による虐待も対象",
            "個人情報保護法：取得目的の明示・同意・適正管理",
            "労働基準法／労働安全衛生法：職員自身の健康と安全を守る",
            "身体拘束廃止（介護保険指定基準）：原則禁止・3要件を満たす場合のみ",
        ],
        note="迷ったら『利用者にとって最善か』『記録に残して説明できるか』で判断。",
    )

    # 18 自己チェック
    add_check_slide(
        prs, META,
        [
            "利用者を氏名＋「さん」で呼んでいる",
            "ケア前に必ず声かけと同意確認をしている",
            "居室・浴室・トイレでプライバシー配慮ができている",
            "家族・利用者情報を施設外で話題にしていない",
            "SNSに業務・利用者に関する投稿をしていない",
            "記録物（ノート・スマホ）を放置せず施錠管理している",
            "電話での情報提供は本人確認後・上司確認後に行っている",
            "迷ったときは一人で判断せず上司・多職種に相談している",
        ],
    )

    # 19 まとめ
    add_summary_slide(
        prs, META,
        [
            "倫理は『目指す姿』、法令は『最低ライン』。両方を意識する",
            "尊厳を守る第一歩は『呼び方』と『声かけ』",
            "守秘義務は退職後も続く。施設外・SNS・電話対応に注意",
            "迷ったら一人で決めず、上司・多職種に相談し記録に残す",
        ],
        next_action=(
            "① 利用者を『○○さん』と呼び、ケア前の声かけを徹底する。"
            "② 休憩室・施設外・SNSでは利用者の個人情報を出さない。"
            "③ 電話での家族対応は本人確認を徹底し、迷ったら上司に確認してから答える。"
            "④ 判断に迷う場面があったら、次回カンファレンスで共有する。"
        ),
    )

    # 20 質疑
    add_qa_slide(prs, META)

    # Attach speaker notes + auto-play narration audio (offline TTS)
    root = Path(__file__).resolve().parent.parent
    audio_dir = root / "audio" / "04"
    attach_narration(
        prs, NARRATION_04, audio_dir,
        deck_key="04", embed_audio=True,
    )

    finalise(prs)

    out = root / "slides" / META.filename
    save(prs, out)
    print(f"created: {out} ({len(prs.slides)} slides)")


if __name__ == "__main__":
    build()
