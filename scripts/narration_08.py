    # 7 3要件
    "例外的に身体拘束が認められる、3要件を学びます。"
    "1つ目、切迫性。本人または他の利用者の生命または身体が危険にさらされる可能性が著しく高いこと。"
    "2つ目、非代替性。身体拘束以外に代替する介護方法がないこと。"
    "3つ目、一時性。身体拘束は一時的なものであること。"
    "この3つ、すべてを満たす、ということが条件です。1つでも欠ければ、拘束してはなりません。"
    "『本人が危ないから』だけでは、要件を満たしていません。",

