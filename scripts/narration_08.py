    "続いて、11項目の後半です。"
    "7つ目、立ち上がる能力のある人の立ち上がりを妨げるようないすを使用する。"
    "8つ目、脱衣やオムツ外しを制限するために、介護衣、つなぎ服を着せる。"
    "9つ目、他人への迷惑行為を防ぐために、ベッドなどに体幹や四肢を紐等で縛る。"
    "10つ目、行動を落ち着かせるために、向精神薬を過剰に服用させる。"
