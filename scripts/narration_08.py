    "厚生労働省が示す、禁止対象となる身体拘束の11項目を、前半と後半に分けて見ていきます。"
    "1つ目、徘徊しないように、車椅子・椅子・ベッドに体幹や四肢を紐等で縛る。"
    "2つ目、転落しないように、ベッドに体幹や四肢を紐等で縛る。"
    "3つ目、自分で降りられないように、ベッドを柵で四方に囲む。"
